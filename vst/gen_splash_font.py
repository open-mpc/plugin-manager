#!/usr/bin/env python3
"""Bakes src/splash_font.h: hinted 8-bit coverage glyphs (DejaVu Sans Bold, printable ASCII) for the update screen
(src/splash.c) at the sizes it draws. Same approach as force-shadow's tools/gen_font_hi.py (glyphs baked at their real
size and drawn 1:1, no upscaling), but proportional: each glyph keeps its own advance.

  python3 vst/gen_splash_font.py [path/to/DejaVuSans-Bold.ttf]
"""
import os, sys
from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
SIZES = {"s": 26, "m": 36, "l": 54}   # small (notes), medium (step line), large (what is happening)
CHARS = [chr(c) for c in range(32, 127)]
PAD = 3   # left room for a negative left bearing (j, y)
here = os.path.dirname(os.path.abspath(__file__))

out = ["/* GENERATED by vst/gen_splash_font.py -- do not edit. DejaVu Sans Bold (Bitstream Vera licence). */\n",
       "typedef struct { unsigned int off; unsigned short w, adv; } sglyph_t;\n",
       f"#define SFONT_PAD {PAD}\n",
       "typedef struct { int h, base; const sglyph_t *g; const unsigned char *px; } sfont_t;\n"]
for name, size in SIZES.items():
    font = ImageFont.truetype(FONT, size)
    asc, desc = font.getmetrics()
    h = asc + desc
    glyphs, px = [], []
    for c in CHARS:
        adv = int(round(font.getlength(c)))
        l, t, r, b = font.getbbox(c, anchor="ls")
        w = max(1, max(r, adv) + PAD + 1)
        im = Image.new("L", (w, h), 0)
        if c != " ":
            ImageDraw.Draw(im).text((PAD, asc), c, font=font, fill=255, anchor="ls")
        glyphs.append((len(px), w, adv))
        px.extend(im.tobytes())
    out.append(f"static const unsigned char sfont_{name}_px[] = {{{','.join(map(str, px))}}};\n")
    out.append(f"static const sglyph_t sfont_{name}_g[] = {{" + ",".join(f"{{{o},{w},{a}}}" for o, w, a in glyphs) + "};\n")
    out.append(f"static const sfont_t sfont_{name} = {{{h}, {asc}, sfont_{name}_g, sfont_{name}_px}};\n")
open(os.path.join(here, "..", "src", "splash_font.h"), "w").write("".join(out))
print("ok")
